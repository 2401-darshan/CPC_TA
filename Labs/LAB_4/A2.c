// print address using single printf and multiple printf statements.

#include <stdio.h>

int main() {
    printf("=== Using Single printf ===\n");
    printf("Address: 123 University Road, Block A, Rajkot, Gujarat, 360005\n\n");

    printf("=== Using Multiple printf ===\n");
    printf("Address Line 1: 123 University Road\n");
    printf("Address Line 2: Block A\n");
    printf("City: Rajkot\n");
    printf("State: Gujarat\n");
    printf("Pincode: 360005\n");

    return 0;
}
